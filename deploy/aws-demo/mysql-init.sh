#!/bin/sh
set -eu

mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<SQL
CREATE DATABASE IF NOT EXISTS cashflashdb;
CREATE DATABASE IF NOT EXISTS cashflash_pspdb;
CREATE USER IF NOT EXISTS '${MYSQL_APP_USER}'@'%' IDENTIFIED BY '${MYSQL_APP_PASSWORD}';
GRANT ALL PRIVILEGES ON cashflashdb.* TO '${MYSQL_APP_USER}'@'%';
GRANT ALL PRIVILEGES ON cashflash_pspdb.* TO '${MYSQL_APP_USER}'@'%';
FLUSH PRIVILEGES;
SQL
